// One-shot: read the GeoJSON, project lon/lat → SVG coords, emit src/data/yunnanGeo.ts
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const geoPath = path.join(__dirname, "geo", "yunnan.geojson");
const outPath = path.join(__dirname, "..", "src", "data", "yunnanGeo.ts");

const VIEWBOX_W = 800;
const VIEWBOX_H = 600;
const PAD = 20;

const ADCODE_TO_DEST = {
  "530100": "kunming",       // 昆明市
  "530500": "tengchong",     // 保山市 (contains 腾冲)
  "530700": "lijiang",       // 丽江市
  "530800": "puer",          // 普洱市
  "532500": "honghe",        // 红河
  "532800": "xishuangbanna", // 西双版纳
  "532900": "dali",          // 大理
  "533300": "nujiang",       // 怒江
  "533400": "shangrila",     // 迪庆
};

const ICONS = {
  kunming: "✦", lijiang: "▲", dali: "❀", shangrila: "❄", nujiang: "⛰",
  tengchong: "♨", puer: "🍃", xishuangbanna: "🌴", honghe: "⛰",
};

const ACTIVE_PALETTE = {
  kunming:       { c1: "#fce7f3", c2: "#fbcfe8", accent: "#ec4899" },
  lijiang:       { c1: "#dbeafe", c2: "#bfdbfe", accent: "#3b82f6" },
  dali:          { c1: "#fef9c3", c2: "#fef08a", accent: "#eab308" },
  shangrila:     { c1: "#ede9fe", c2: "#ddd6fe", accent: "#8b5cf6" },
  nujiang:       { c1: "#fef3c7", c2: "#fde68a", accent: "#f59e0b" },
  tengchong:     { c1: "#fed7aa", c2: "#fdba74", accent: "#f97316" },
  puer:          { c1: "#d1fae5", c2: "#a7f3d0", accent: "#10b981" },
  xishuangbanna: { c1: "#ccfbf1", c2: "#99f6e4", accent: "#14b8a6" },
  honghe:        { c1: "#fee2e2", c2: "#fecaca", accent: "#ef4444" },
};

const geo = JSON.parse(fs.readFileSync(geoPath, "utf8"));

// Compute bounding box of all features
let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
for (const f of geo.features) {
  const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
  for (const poly of polys) {
    for (const ring of poly) {
      for (const [lon, lat] of ring) {
        if (lon < minLon) minLon = lon;
        if (lon > maxLon) maxLon = lon;
        if (lat < minLat) minLat = lat;
        if (lat > maxLat) maxLat = lat;
      }
    }
  }
}

// Equirectangular with cos-latitude correction
const midLat = (minLat + maxLat) / 2;
const cos = Math.cos((midLat * Math.PI) / 180);
const lonSpan = (maxLon - minLon) * cos;
const latSpan = maxLat - minLat;
const scaleX = (VIEWBOX_W - PAD * 2) / lonSpan;
const scaleY = (VIEWBOX_H - PAD * 2) / latSpan;
const scale = Math.min(scaleX, scaleY);
// center the projection
const projW = lonSpan * scale;
const projH = latSpan * scale;
const offsetX = (VIEWBOX_W - projW) / 2;
const offsetY = (VIEWBOX_H - projH) / 2;

const project = (lon, lat) => {
  const x = offsetX + (lon - minLon) * cos * scale;
  const y = offsetY + (maxLat - lat) * scale; // flip Y
  return [Number(x.toFixed(2)), Number(y.toFixed(2))];
};

const ringToPath = (ring) => {
  let d = "";
  for (let i = 0; i < ring.length; i++) {
    const [x, y] = project(ring[i][0], ring[i][1]);
    d += (i === 0 ? "M" : "L") + x + "," + y;
  }
  return d + "Z";
};

const features = [];
for (const f of geo.features) {
  const adcode = String(f.properties.adcode);
  const name = f.properties.name;
  const center = f.properties.center; // [lon, lat]
  const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
  // Use only the largest ring per polygon (drops tiny islands inside MultiPolygons but keeps mainland)
  let path = "";
  for (const poly of polys) {
    // poly[0] is outer ring, poly[1..] are holes — for visual simplicity just draw outer
    path += ringToPath(poly[0]);
  }
  const [labelX, labelY] = center
    ? project(center[0], center[1])
    : project((minLon + maxLon) / 2, (minLat + maxLat) / 2);

  const destinationId = ADCODE_TO_DEST[adcode] || null;
  features.push({
    adcode,
    name,
    destinationId,
    icon: destinationId ? ICONS[destinationId] : "",
    palette: destinationId ? ACTIVE_PALETTE[destinationId] : null,
    path,
    labelX,
    labelY,
  });
}

// Compute outer hull (province border) — simply concatenate all paths
// (Browser will draw all rings; we wrap with the same path for outline below.)
const outline = features.map((f) => f.path).join(" ");

const out =
  `// AUTO-GENERATED by scripts/build-yunnan-geo.mjs — do not edit by hand.\n` +
  `// Source: DataV.GeoAtlas (https://geo.datav.aliyun.com/areas_v3/bound/530000_full.json)\n` +
  `\n` +
  `export interface PrefectureFeature {\n` +
  `  adcode: string;\n` +
  `  name: string;\n` +
  `  destinationId: string | null;\n` +
  `  icon: string;\n` +
  `  palette: { c1: string; c2: string; accent: string } | null;\n` +
  `  path: string;\n` +
  `  labelX: number;\n` +
  `  labelY: number;\n` +
  `}\n` +
  `\n` +
  `export const VIEWBOX_W = ${VIEWBOX_W};\n` +
  `export const VIEWBOX_H = ${VIEWBOX_H};\n` +
  `\n` +
  `export const yunnanOutline = ${JSON.stringify(outline)};\n` +
  `\n` +
  `export const prefectures: PrefectureFeature[] = ${JSON.stringify(features, null, 2)};\n` +
  `\n` +
  `export default prefectures;\n`;

fs.writeFileSync(outPath, out);

console.log("✓ wrote src/data/yunnanGeo.ts");
console.log("  features:", features.length);
console.log("  active (with destinations):", features.filter((f) => f.destinationId).length);
console.log("  bbox lon:", minLon.toFixed(3), "→", maxLon.toFixed(3));
console.log("  bbox lat:", minLat.toFixed(3), "→", maxLat.toFixed(3));
console.log("  scale:", scale.toFixed(2), "px/deg");
